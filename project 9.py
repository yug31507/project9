                values = self.data[column].dropna().head(30)

                if values.empty:
                    print("No data available to plot.")
                    return

                fig, ax = plt.subplots(figsize=(10, 5))
                values.plot(kind="line", marker="o", ax=ax, color='limegreen', markerfacecolor='green')
                ax.set_title("Line Plot (First 30 rows)")
                ax.set_ylabel(column)
                ax.grid(True, alpha=0.3)

