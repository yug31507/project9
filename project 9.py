                if plot_data.empty:
                    print("No complete rows available for plotting.")
                    return

                fig, ax = plt.subplots(figsize=(8, 6))
                ax.scatter(plot_data[x_col], plot_data[y_col], alpha=0.6, color='lightgreen', edgecolors='green')
                ax.set_xlabel(x_col)
                ax.set_ylabel(y_col)
                ax.set_title("Scatter Plot")
                ax.grid(True, alpha=0.3)

